            <div class="content">
                <h2>Charte du bien-être et du vivre ensemble lors d’évènements festifs</h2>
    
                <h3>Introduction</h3>
                <p>
                    Cette charte s'applique à tous les étudiants, y compris aux membres organisateurs, sans distinction de leur rôle au sein de l’organisation ou des affinités qu’ils peuvent avoir avec les autres membres de celle-ci.
                </p>
    
    
                <h3>Article 1 : Droits et devoirs de l’organisateur</h3>
                <h4>Droits</h4>
                <ul>
                    <li>Les membres organisateurs se réservent le droit de refuser l'accès à une personne aux événements organisés en cas de sanctions prises par le CA suite à des faits antérieurs survenus lors de précédents événements.</li>
                    <li>Les organisateurs se réservent le droit de stopper la distribution d’alcool aux personnes n’étant plus en possession de leurs moyens.</li>
                    <li>Les membres organisateurs se réservent le droit, en cas de comportement inapproprié ou dangereux, d’en référer aux autorités supérieures (administration, forces de l’ordre).</li>
                    <li>Les organisateurs se réservent le droit d’exclure quelqu’un de l'événement s'il a un comportement dangereux pour lui-même ou pour autrui.</li>
                </ul>
    
                <h4>Devoirs</h4>
                <ul>
                    <li>Les organisateurs doivent nommer des référents HVSS totalement sobres et reconnaissables, ayant pour unique activité leur mission, qui veilleront au bien-être de tous durant la soirée.</li>
                    <li>Ils doivent respecter la volonté, l’anonymat et l’intimité des victimes. Il est proscrit de raconter des faits sans la permission des personnes concernées.</li>
                    <li>Les organisateurs doivent créer et maintenir une safe place pendant l'événement.</li>
                    <li>Ils doivent mettre en place un feedback de la soirée afin de recueillir des plaintes ou retours anonymes.</li>
                    <li>Les référents HVSS doivent prendre en considération toutes les plaintes et avertissements concernant des comportements déplacés, indépendamment de leur relation avec l’accusé, et mettre en place les mesures appropriées.</li>
                    <li>Les organisateurs doivent fournir des accessoires assurant le bon déroulement des événements (préservatifs, capotes de verres, éthylotests, bouchons d’oreilles, bouteilles d'eau).</li>
                    <li>Ils doivent éviter tout comportement nuisible au bon déroulement des événements (alcool, violence, etc.) sous peine d'exclusion temporaire en attente de sanctions par le CA.</li>
                    <li>Les organisateurs doivent communiquer sur les risques festifs avant et après l'événement.</li>
                    <li>Ils doivent tout mettre en œuvre pour assurer la sécurité des participants.</li>
                </ul>
    
                <h3>Article 2 : Droits et devoirs du participant</h3>
                <h4>Droits</h4>
                <ul>
                    <li>Toute personne doit se sentir libre de refuser un acte qu’elle qualifie de dégradant ou dérangeant.</li>
                    <li>Une personne qui ne souhaite pas boire d’alcool ne doit pas ressentir de pression à ce sujet.</li>
                    <li>Toute personne se sentant mal à l’aise vis-à-vis du comportement d’un autre participant doit se sentir légitime d’en parler aux référents.</li>
                </ul>
    
                <h4>Devoirs</h4>
                <ul>
                    <li>Les participants ne doivent être un danger ni pour eux-mêmes ni pour les autres.</li>
                    <li>Ils ne doivent pas pratiquer de bizutage.</li>
                    <li>Ils ne doivent pas tenir de propos discriminatoires (racistes, sexistes, xénophobes, etc.).</li>
                    <li>Ils doivent assister toute personne en danger ou en difficulté et la mettre en contact avec un responsable de l’organisation.</li>
                    <li>Ils ne doivent pas amener de substances illicites.</li>
                    <li>Ils ne doivent pas adopter de comportements violents, que ce soit par les actes ou les paroles.</li>
                    <li>Ils ne doivent pas avoir de comportements déplacés ou à caractère HVSS.</li>
                </ul>
    
                <h3>Article 3 : Sanctions</h3>
                <p>
                    Durant l'événement, selon la gravité des faits reprochés, les staffs peuvent prononcer des sanctions telles que l’interdiction de consommer de l’alcool ou l’exclusion de l’événement. Après l’événement, le CA peut décider de sanctions supplémentaires, allant du blâme à l’exclusion définitive de l’association.
                </p>
    
                <h3>Annexe</h3>
                <ul>
                    <li><strong>CA :</strong> Conseil d’administration composé du bureau du BDE ainsi que des responsables de chaque pôle composant celui-ci.</li>
                    <li><strong>Référents HVSS :</strong> Membres du staff désignés pour prévenir et lutter contre les agissements sexistes ainsi que les faits de harcèlement et de violence sexuelle lors d'événements.</li>
                    <li><strong>Safe place :</strong> Lieu où chaque personne peut se réfugier si elle a été victime ou risque d'être victime d'injures, de harcèlement ou d'agressions.</li>
                    <li><strong>Risques festifs :</strong> Dangers liés aux fêtes et soirées, comme l'excès d'alcool, la consommation de drogues, les accidents, les violences et les comportements à risque.</li>
                    <li><strong>Bizutage :</strong> Incitation ou contrainte d’une personne à agir à l’encontre de sa volonté.</li>
                    <li><strong>HVSS :</strong> Harcèlement, violence sexiste et sexuelle.</li>
                </ul>

